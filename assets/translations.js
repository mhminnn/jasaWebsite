function setLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update Language Toggle Buttons (Desktop)
    const btnId = document.getElementById('btn-lang-id');
    const btnEn = document.getElementById('btn-lang-en');
    if (btnId && btnEn) {
        if (lang === 'id') {
            btnId.classList.add('text-primary', 'font-bold');
            btnId.classList.remove('text-on-surface-variant');
            btnEn.classList.add('text-on-surface-variant');
            btnEn.classList.remove('text-primary', 'font-bold');
        } else {
            btnEn.classList.add('text-primary', 'font-bold');
            btnEn.classList.remove('text-on-surface-variant');
            btnId.classList.add('text-on-surface-variant');
            btnId.classList.remove('text-primary', 'font-bold');
        }
    }
    
    // Update Language Toggle Buttons (Mobile)
    const btnIdMob = document.getElementById('btn-lang-id-mob');
    const btnEnMob = document.getElementById('btn-lang-en-mob');
    if (btnIdMob && btnEnMob) {
        if (lang === 'id') {
            btnIdMob.classList.add('text-primary', 'font-bold');
            btnIdMob.classList.remove('text-on-surface-variant');
            btnEnMob.classList.add('text-on-surface-variant');
            btnEnMob.classList.remove('text-primary', 'font-bold');
        } else {
            btnEnMob.classList.add('text-primary', 'font-bold');
            btnEnMob.classList.remove('text-on-surface-variant');
            btnIdMob.classList.add('text-on-surface-variant');
            btnIdMob.classList.remove('text-primary', 'font-bold');
        }
    }

    localStorage.setItem('mincode_lang', lang);
}

function initLanguage() {
    const savedLang = localStorage.getItem('mincode_lang') || 'id';
    setLanguage(savedLang);
}

document.addEventListener('DOMContentLoaded', initLanguage);
